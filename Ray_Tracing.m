viewer = siteviewer(Buildings="_seongnam_map.osm", Basemap="topographic");

tx = txsite(Name="Small cell transmitter", ...
    Latitude=37.4515, ...
    Longitude=127.1294, ...
    AntennaHeight=25, ...
    TransmitterPower=60, ...
    TransmitterFrequency=4.7e9);
show(tx)

% 첫 번째 전파 모델 (반사 없음)
rtpm = propagationModel("raytracing", ...
    Method="sbr", ...
    MaxNumReflections=0, ...
    BuildingsMaterial="PEC", ...
    TerrainMaterial="PEC");

rx = rxsite(Name="Small cell receiver", ...
    Latitude=37.4506, ...
    Longitude=127.1295, ...
    AntennaHeight=1.5);
los(tx, rx)

% 두 번째 전파 모델 (반사 및 회절 포함) - 새로 정의
rtPlusWeather = propagationModel("raytracing", ...
    Method="sbr", ...
    MaxNumReflections=2, ...
    MaxNumDiffractions=0, ...
    AngularSeparation="high", ...
    BuildingsMaterial="PEC", ...
    TerrainMaterial="PEC");

clearMap(viewer)
show(tx)

coverage(tx, rtPlusWeather, ...
    SignalStrengths=-120:-5, ...
    MaxRange=250, ...
    Resolution=2, ...
    Transparency=0.6)